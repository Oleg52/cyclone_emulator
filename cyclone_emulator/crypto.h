static const uint8_t *tbl_row(unsigned index)
{
    if (index < TAB_LO || index > TAB_HI)
        return 0;
    return TBL[index - TAB_LO];
}

/* ---------------------------------------------------------------- forward codec */

static uint8_t rev_byt(uint8_t v)
{
    uint8_t r = 0;
    for (int i = 0; i < 8; i++)
        if (v & (1u << i))
            r |= (uint8_t)(1u << (7 - i));
    return r;
}

static void rev_buf(uint8_t b[12])
{
    uint8_t c[12];
    memcpy(c, b, 12);
    for (int i = 0; i < 12; i++)
        b[i] = rev_byt(c[11 - i]);
}

/* Rotate the 32-bit big-endian word at b[p..p+3] right by k bits. */
static void crr32k(uint8_t b[12], int p, int k)
{
    uint32_t x = ((uint32_t)b[p]   << 24) | ((uint32_t)b[p+1] << 16) |
                 ((uint32_t)b[p+2] <<  8) |  (uint32_t)b[p+3];
    k %= 32;
    if (k)
        x = (x >> k) | (x << (32 - k));
    b[p]   = (uint8_t)(x >> 24);
    b[p+1] = (uint8_t)(x >> 16);
    b[p+2] = (uint8_t)(x >>  8);
    b[p+3] = (uint8_t) x;
}

/* Nonlinear mix over byte groups {i, i+4, i+8}. */
static void xor_or_b(uint8_t b[12])
{
    uint8_t c[12];
    memcpy(c, b, 12);
    for (int i = 0; i < 12; i++)
        b[i] = (uint8_t)(c[i] ^ (c[(i + 4) % 12] | (uint8_t)~c[(i + 8) % 12]));
}

/* XOR the table row, plus the round key into bytes 2,3,8,9. */
static void scr_stt(uint8_t b[12], const uint8_t tab[12], const uint8_t key[12], int round)
{
    for (int i = 0; i < 12; i++)
        b[i] ^= tab[i];
    b[2] ^= key[round];
    b[3] ^= key[round];
    b[8] ^= key[round];
    b[9] ^= key[round];
}

static void permut(uint8_t b[12])
{
    uint8_t out[12] = {0}, seen[12] = {0}, parity = 0;
    for (int s = 0; s < 12; s++) {
        uint8_t v = b[s];
        parity ^= v;
        for (int j = 0; j < 5; j++) {
            int d = PERM[s][j];
            out[d] = seen[d] ? (uint8_t)(v ^ out[d]) : v;
            seen[d] = 1;
        }
    }
    for (int i = 0; i < 12; i++)
        b[i] = (uint8_t)(out[i] ^ parity);
}

static void codec_n(uint8_t b[12], const uint8_t tab[12], const uint8_t key[12])
{
    for (int round = 0; round < 11; round++) {
        scr_stt(b, tab, key, round);
        permut(b);
        crr32k(b, 0, 10);
        crr32k(b, 8, 31);
        xor_or_b(b);
        crr32k(b, 8, 10);
        crr32k(b, 0, 31);
    }
    scr_stt(b, tab, key, 11);
    permut(b);
    rev_buf(b);
}

static uint8_t crc8(const uint8_t *d, int n)
{
    uint8_t c = 0;
    for (int i = 0; i < n; i++) {
        c ^= d[i];
        for (int j = 0; j < 8; j++)
            c = (c & 0x80) ? (uint8_t)((c << 1) ^ 0x07) : (uint8_t)(c << 1);
    }
    return c;
}

/* ---------------------------------------------------------------- inverse codec */

static void inv_permut(uint8_t b[12])
{
    uint8_t out[12];
    for (int i = 0; i < 12; i++) {
        uint8_t v = 0;
        uint16_t mask = PMINV[i];
        for (int j = 0; j < 12; j++)
            if (mask & (1u << j))
                v ^= b[j];
        out[i] = v;
    }
    memcpy(b, out, 12);
}

/* Invert xor_or_b by solving each bit-plane of every {g, g+4, g+8} group. */
static void inv_xor_or_b(uint8_t b[12])
{
    uint8_t out[12];
    memcpy(out, b, 12);
    for (int g = 0; g < 4; g++) {
        uint8_t ya = b[g], yb = b[g + 4], yc = b[g + 8];
        uint8_t ra = 0, rb = 0, rc = 0;
        for (int bit = 0; bit < 8; bit++) {
            int ta = (ya >> bit) & 1, tb = (yb >> bit) & 1, tc = (yc >> bit) & 1;
            for (int xa = 0; xa < 2; xa++)
            for (int xb = 0; xb < 2; xb++)
            for (int xc = 0; xc < 2; xc++) {
                int oa = xa ^ (xb | (1 - xc));
                int ob = xb ^ (xc | (1 - xa));
                int oc = xc ^ (xa | (1 - xb));
                if (oa == ta && ob == tb && oc == tc) {
                    ra |= xa << bit;
                    rb |= xb << bit;
                    rc |= xc << bit;
                }
            }
        }
        out[g] = ra;
        out[g + 4] = rb;
        out[g + 8] = rc;
    }
    memcpy(b, out, 12);
}

static void inv_codec(uint8_t b[12], const uint8_t tab[12], const uint8_t key[12])
{
    rev_buf(b);
    inv_permut(b);
    scr_stt(b, tab, key, 11);
    for (int round = 10; round >= 0; round--) {
        crr32k(b, 0, 1);
        crr32k(b, 8, 22);
        inv_xor_or_b(b);
        crr32k(b, 8, 1);
        crr32k(b, 0, 22);
        inv_permut(b);
        scr_stt(b, tab, key, round);
    }
}

/* ---------------------------------------------------------------- public API */

/* Decode a 13-byte MSID into flashCRC[4], cobba[4], hash[4]. Returns 0 on a
 * selector outside the table range. */
int msid_decode(const uint8_t msid[13], uint8_t flashcrc[4], uint8_t cobba[4], uint8_t hash[4], uint8_t full[12])
{
    const uint8_t *row = tbl_row(msid[0]);
    if (!row)
        return 0;

    uint8_t b[12];
    memcpy(b, msid + 1, 12);
    inv_codec(b, row, ENCOD);

    if (flashcrc) memcpy(flashcrc, b,     4);
    if (cobba)    memcpy(cobba,    b + 4, 4);
    if (hash)     memcpy(hash,     b + 8, 4);
    if (full)     memcpy(full,     b, sizeof(b));
    return 1;
}

/* Plaintext-tail convention for the 0x84 case. Decode and the codec are the
 * same across all tools; only these 8 tail bytes differ between generators:
 *   FAID_HASH    tail = [ ppm^0xFF | hash ]   (genuine Cyclone smartcard)
 *   FAID_PPMCRC  tail = [ ppm^0xFF | 0000 ]   (UFS flasher)
 *   FAID_ZERO    tail = [ 0000 | 0000 ]
 *   FAID_CONST   tail = 1BDC000001E636B0      (fixed tool watermark) */
enum { FAID_PPMCRC = 0, FAID_ZERO = 1, FAID_CONST = 2, FAID_HASH = 3 };

int msid_to_faid_mode(const uint8_t msid[13], uint8_t faid[12], int mode)
{
    static const uint8_t mask[4]      = {0x17, 0xCA, 0x60, 0x89};
    static const uint8_t WATERMARK[8] = {0x1B, 0xDC, 0x00, 0x00, 0x01, 0xE6, 0x36, 0xB0};

    uint8_t flashcrc[4], cobba[4], hash[4];
    if (!msid_decode(msid, flashcrc, cobba, hash, NULL))
        return 0;

    const uint8_t *erow = tbl_row(hash[0]);
    if (!erow)
        return 0;

    uint8_t ppm[4];
    int i;
    for (i = 0; i < 4; i++)
        ppm[i] = (uint8_t)(flashcrc[i] ^ mask[i]);

    uint8_t P[12] = {0};
    memcpy(P, ppm, 4);

    if (msid[0] == 0x84) {
        if (mode == FAID_CONST) {
            memcpy(P + 4, WATERMARK, 8);
        } else if (mode == FAID_ZERO) {
            ; /* tail stays zero */
        } else {
            for (int i = 0; i < 4; i++)
                P[4 + i] = (uint8_t)(ppm[i] ^ 0xFF);
            if (mode == FAID_HASH)
                memcpy(P + 8, hash, 4);
        }
    } else {
        uint8_t full[12] = {0};
        memcpy(full, ppm, 4);
        for (int i = 0; i < 4; i++)
            full[4 + i] = (uint8_t)(ppm[i] ^ 0xFF);
        P[4] = crc8(full, 12);
    }

    uint8_t tab[12];
    for (i = 0; i < 12; i++)
        tab[i] = (uint8_t)(erow[i] ^ (i < 4 ? cobba[i] : 0));

    memcpy(faid, P, 12);
    codec_n(faid, tab, ENCOD);
    return 1;
}

int msid_to_faid(const uint8_t msid[13], uint8_t faid[12])
{
    return msid_to_faid_mode(msid, faid, FAID_HASH);
}

